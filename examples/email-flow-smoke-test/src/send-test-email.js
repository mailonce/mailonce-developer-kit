import "dotenv/config";

import { randomBytes, randomInt } from "node:crypto";
import nodemailer from "nodemailer";

function requiredEnv(name) {
  const value = process.env[name]?.trim();
  if (!value) {
    throw new Error(`Missing required environment variable: ${name}`);
  }
  return value;
}

function parseArgs(argv) {
  let to;
  let type = "both";

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];

    if (arg === "--to") {
      to = argv[i + 1];
      i += 1;
      continue;
    }

    if (arg === "--type") {
      const value = argv[i + 1];
      if (!["otp", "link", "both"].includes(value)) {
        throw new Error('Expected --type to be one of: "otp", "link", "both".');
      }
      type = value;
      i += 1;
      continue;
    }

    if (arg === "--help" || arg === "-h") {
      console.log("Usage: npm run send -- --to <temporary-email> --type <otp|link|both>");
      process.exit(0);
    }

    throw new Error(`Unknown argument: ${arg}`);
  }

  if (!to || !/^\S+@\S+\.\S+$/.test(to)) {
    throw new Error("Provide a valid recipient with --to <temporary-email>.");
  }

  return { to, type };
}

function escapeHtml(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

async function main() {
  const { to, type } = parseArgs(process.argv.slice(2));

  const host = requiredEnv("SMTP_HOST");
  const port = Number(requiredEnv("SMTP_PORT"));
  const secureValue = requiredEnv("SMTP_SECURE").toLowerCase();
  const user = requiredEnv("SMTP_USER");
  const pass = requiredEnv("SMTP_PASS");
  const from = requiredEnv("SMTP_FROM");

  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    throw new Error("SMTP_PORT must be an integer between 1 and 65535.");
  }

  if (secureValue !== "true" && secureValue !== "false") {
    throw new Error('SMTP_SECURE must be either "true" or "false".');
  }

  const otp = String(randomInt(0, 1_000_000)).padStart(6, "0");
  const token = randomBytes(24).toString("hex");

  let verificationUrl;
  if (type === "link" || type === "both") {
    const base = requiredEnv("VERIFICATION_BASE_URL");
    const url = new URL(base);
    url.searchParams.set("token", token);
    verificationUrl = url.toString();
  }

  const textParts = ["MailOnce developer smoke test", ""];
  const htmlParts = ["<h1>MailOnce developer smoke test</h1>"];

  if (type === "otp" || type === "both") {
    textParts.push(`One-time password: ${otp}`, "");
    htmlParts.push(`<p>One-time password: <strong>${escapeHtml(otp)}</strong></p>`);
  }

  if (verificationUrl) {
    textParts.push(`Verification link: ${verificationUrl}`, "");
    htmlParts.push(
      `<p>Verification link: <a href="${escapeHtml(verificationUrl)}">${escapeHtml(verificationUrl)}</a></p>`,
    );
  }

  textParts.push("This message was generated by the MailOnce Developer Kit example.");
  htmlParts.push("<p>This message was generated by the MailOnce Developer Kit example.</p>");

  const transporter = nodemailer.createTransport({
    host,
    port,
    secure: secureValue === "true",
    auth: { user, pass },
  });

  await transporter.verify();

  const result = await transporter.sendMail({
    from,
    to,
    subject: `MailOnce test: ${type}`,
    text: textParts.join("\n"),
    html: htmlParts.join("\n"),
  });

  console.log(`Sent test email to: ${to}`);
  console.log(`Message type: ${type}`);
  console.log(`SMTP message id: ${result.messageId}`);

  if (type === "otp" || type === "both") {
    console.log(`Expected OTP: ${otp}`);
  }

  if (verificationUrl) {
    console.log(`Expected verification URL: ${verificationUrl}`);
  }
}

main().catch((error) => {
  const message = error instanceof Error ? error.message : String(error);
  console.error(`Error: ${message}`);
  process.exitCode = 1;
});
